def main() -> None:
    with open(CONFIG, encoding="utf-8") as f:
        data = json.load(f)

    dims = data["nodes"]["outline"]["dimensions"]
    genre_dim = next(d for d in dims if d["key"] == "genre")
    chips = genre_dim["chips"]

    labels = [c["label"] for c in chips]
    missing = [l for l in labels if l not in FLAVORS]
    if missing:
        print("以下流派卡缺少 flavors 定义:", missing)
        sys.exit(1)

    for chip in chips:
        chip["flavors"] = FLAVORS[chip["label"]]

    keys = [d["key"] for d in dims]
    insert_at = keys.index("elements") + 1
    existing = {d["key"] for d in dims}
    for offset, dim in enumerate(NEW_DIMENSIONS):
        if dim["key"] not in existing:
            dims.insert(insert_at + offset, dim)

    with open(CONFIG, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"完成:{len(chips)} 张流派卡已带 flavors;新维度: lead_gender/romance/opening/protagonist")


if __name__ == "__main__":
    main()
