"""故事骨架胶囊:概念/方向层的「结构配方」——短剧爆款的结构套路库。

这是 prompts/dna_capsules(味道锚,管「要哪种质感」)与
prompts/style_capsules(文风,管「怎么写句子」)在 **情节组织** 维度的对应物:
管「故事按什么配方长出来」。

病根:抖音短剧改编剧(赘婿打脸/战神归来/前世今生/异国财阀恋…)的核心不在
文笔也不在味道,而在 **结构配方**——开局即冲突、身份错位做引擎、每章一个
反转/卡点。模型默认按「全网文平均」的长篇节奏写:慢热、渐进、伏笔深埋。
用户在创作蓝本里写「山东小伙去韩国做练习生认识财阀大小姐」,出来的仍是
四平八稳的长篇开局——不是模型不会写,是没人告诉它「按哪套配方组织情节」。

每个胶囊含:
- formula:结构配方(核心错位/故事引擎——情节靠什么一直往前拱)
- rhythm:节奏规则(钩子密度/章末卡点/打脸周期,可直接执行的硬要求)
- beats:必备桥段(这一挂的观众就是冲这些来的,漏了就"不像")
- opener:开场钩子示范(原创短段,学结构不搬内容——few-shot 正例)

版权红线(沿用 dna_capsules/style_capsules 纪律):opener 一律本项目自撰的
原创短段,非任何原作节选;comps_hint 只作参照指路名,不搬其内容。
前端须标注「结构参考·非原作节选」。

注入路径:并入 dna_block_of(assembler),顺 style_block 追加,不新增 prompt
占位符(与前两个胶囊家族一致:一处注入多处生效)。DNA 未选骨架 → 空串,
prompt 一字不变(评测基线不受影响)。
"""
