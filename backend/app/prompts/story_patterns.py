def get_story_pattern(key: str) -> StoryPattern | None:
    return next((p for p in STORY_PATTERNS if p.key == key), None)


def pattern_choices() -> list[dict]:
    """给前端下拉/API 的选项(带简介,不含 opener 正文——选择即可,不必先读示范)。"""
    return [
        {
            "key": p.key,
            "name": p.name,
            "comps_hint": p.comps_hint,
            "formula": p.formula,
            "rhythm": p.rhythm,
        }
        for p in STORY_PATTERNS
    ]


def render_pattern_block(pattern_key: str = "") -> str:
    """渲染「故事骨架」注入块;未选骨架 → 空串(prompt 该块整体省略)。

    与 render_dna_capsule_block 同套路:结构胶囊的信息密度高(formula/rhythm/
    beats 都是可执行指令),整块直接注入;opener 作 few-shot 正例压轴。
    """
    p = get_story_pattern(pattern_key)
    if p is None:
        return ""
    lines = [
        "【故事骨架(结构锚·最高优先级:情节组织严格按这套配方,不要写成慢热长篇)】",
        f"- 骨架配方:{p.formula}",
        f"- 节奏规则:{p.rhythm}",
    ]
    if p.beats:
        lines.append(f"- 必备桥段(观众就是冲这些来的,不可缺席):{'、'.join(p.beats)}")
    if p.opener:
        lines.append(
            "- 开场示范(本项目自撰的原创短段,只学结构与力度,不搬内容):\n" + p.opener
        )
    return "\n".join(lines) + "\n"
