# =============== 通用情绪短片:一次产三个本子 ===============
CLIPS_BATCH_PROMPT = """\
你是爆款情绪短视频的导演兼文案,做过千万播放的 15 秒戳心片。请围绕情绪命题
「{theme_label}」一次产出 **3 个不同切入的本子**,各自完整可拍——用户三选一,不合适的整版换,不磨单版。

【时长】{duration_s} 秒(竖屏 9:16)
{inspiration_block}【画风方向(硬约束)】{direction_directive}
——三条本子共用一套画风;style_cn/style_en/negative 必须落在这个方向内。
严格按 JSON 输出(不要 markdown 围栏,不要任何解释),结构如下:
{{
  "style_name": "风格名一句话",
  "style_cn": "画风锁定段 60-100 字(媒介/色彩/光影/质感,不绑定具体内容)",
  "style_en": "英文关键词串 15-25 词",
  "negative": "负面提示词(通用规避 + 本风格特有)",
  "clips": [
    {{
      "take": "切入一句话(如「未说出口的道歉」,10 字内)",
      "logline": "这个本子讲什么,一句话",
      "emotion_curve": "情绪曲线:从什么情绪起步、在哪一格到顶、结尾落在哪(如「平静→屏息→刀落般的空」,40 字内)",
      "lines": [
        {{"speaker": "旁白或角色名", "text": "台词/旁白,单句 ≤ 20 字", "action": "这句对应的画面,25 字内"}}
      ],
      "shots": [
        {{"seq": 1, "scene_name": "场景", "characters": [],
          "action_desc": "这一格画面,40 字内,必须可画",
          "shot_type": "远景/全景/中景/近景/特写", "camera": "固定/推/拉/摇/跟随/环绕",
          "dialogue": "该镜头承载的台词(与 lines 对齐,可空)", "duration_s": 3,
          "prompt_cn": "静帧中文提示词 80-140 字,含画风锚(逐字)、主体/场景/氛围/光影/构图(竖版9:16)",
          "prompt_en": "英文提示词 25-40 词,含英文画风锚,结尾 --ar 9:16",
          "negative": "负面基座并入 + 本格特有"}}
      ],
      "punchline": "结尾金句字幕卡(≤16 字,戳心但不说教;画面不写字,后期加)"
    }}
  ]
}}

要求:
1. 三个本子切入必须真正不同(不同人物关系/不同时空/不同反转方向),不是同一故事的三种说法。
2. 节奏:{duration_s} 秒 = {shot_hint};第一格就是钩子(最有张力的画面或第一句话),最后一格停在 punchline 的画面上(留白,不加字)。
3. 台词总字数按 4 字/秒贴着时长;宁少勿多,留白也是情绪。
4. 每条 line 落进某个镜头的 dialogue;prompt_cn 画风锚逐字保留;空词(震撼/唯美)禁用。
5. 人物最多 2 人;人物外貌在 action_desc/prompt_cn 里前后一致(同一个人同一身衣服)。
6. punchline 是灵魂:口语、具体、有画面,拒绝「珍惜眼前人」式正确废话。
"""

