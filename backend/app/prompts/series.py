# app/prompts/series.py
# -*- coding: utf-8 -*-
"""角色系列短片提示词:固定主角的 5-15 秒系列短视频,轻量单条直出。

这条线的产品心智与三本子工坊相反——**主角是资产,剧情是耗材**:
- 定妆描述(look)是全系列一致性的锚,生成提示词时逐字硬注入,LLM 不得改写;
- 每集只喂一段剧情,单发直出一条可直接投喂图文生视频模型(minimax 图生视频)
  的成片提示词——**篇幅自由**:短到一两百字、长到上千字都行(用户明确要求,
  160-280 字的三线公约在这条线不适用,是产品决策不是口径分叉),细节密度
  按剧情需要,把该写的写全即可,不为凑字数注水、也不为省字数砍要素。

两条模板:
- SERIES_LOOK_PROMPT:一句话概念 → 完整定妆描述(建角色时 AI 代写草稿);
- SERIES_EPISODE_PROMPT:定妆 + 剧情 + 时长/画风 → {title, prompt_cn, negative}。

**铁律必须出现在提示词正文里**(与三线同一教训:写在注释里模型看不见)。
"""
from __future__ import annotations

# =============== ① 一句话概念 → 定妆描述(建角色时代写草稿) ===============
SERIES_LOOK_PROMPT = """\
你是角色设计总监,给一支竖屏短视频系列设计**固定主角**——这个角色要连拍几十集,
定妆描述就是全系列的一致性锚,每一集的每一帧都靠它锁形象,所以必须写到
「拿去文生图就能出定妆照」的密度。篇幅长短不拘:把该写的写全即可,
简单角色一两百字、复杂角色上千字都可以,不为凑字数注水。

【主角概念(用户原话,不许擅自加设定之外的元素)】{brief}
【画风方向(硬约束)】{direction_directive}
{hints_block}
严格按 JSON 输出(不要 markdown 围栏,不要任何解释):
{{
  "look": "定妆描述,一段连贯中文,长短按角色复杂度自然决定"
}}

look 必须逐项写清(写成可直接粘进视频提示词的一段话,不列编号):
1. 物种/品类与年龄感(如「一只成年小浣熊,体态圆润敦实」);
2. 体型大小与比例(与常见物体的相对大小,给视频模型当尺度参照);
3. 毛色/肤色分布——具体到部位(眼圈、耳尖、四肢、尾巴各是什么色);
4. 五官与脸部特征(眼形、鼻头、嘴、标志性表情肌);
5. 标志性外貌记忆点(一块独特的斑、缺了的牙、翘起的一撮毛——跨集认脸靠它);
6. 常驻服装与配饰(款式+颜色+材质,全系列固定不换);
7. 性格神态与招牌动作(写在神态里,不写具体剧情);
8. 整体气质一句话收尾(给运镜与配乐定调)。
只写角色本身,不写场景、不写剧情、不写镜头。"""

# =============== ② 定妆 + 剧情 → 一条成片提示词 ===============
SERIES_EPISODE_PROMPT = """\
你是竖屏短视频导演兼摄影指导,给一位**固定主角**拍一支 {duration_s} 秒的单镜头短片。
这个系列已经拍了很多集,观众认的就是这张脸——主角形象一个字都不许走样。

【主角定妆(最高优先级铁律:下述描述必须**逐字**进入提示词的主角描写,
不得改写、缩写、换词或再创作)】
{look}
【画风方向(硬约束)】{direction_directive}
{hints_block}
【本集剧情(用户给的,主线不得变更,可补细节与起承转合)】
{plot}
严格按 JSON 输出(不要 markdown 围栏,不要任何解释):
{{
  "title": "本集标题,12 字内",
  "prompt_cn": "成片提示词,一段式中文,长短按剧情密度自然决定",
  "negative": "画面负面提示词,80 字内"
}}

prompt_cn 的硬性要求(要素缺一不可;篇幅自由——简单剧情一两百字、
复杂剧情上千字都行,写全即止,不为凑字数注水、不为省字数砍要素):
1. **人物**:主角描写以定妆描述为骨架逐字展开,叠加本集的动作与表情变化
   (动作按秒铺开:第几秒在做什么、表情怎么变);
2. **场景**:具体空间 + 关键陈设 + 位置关系(写「杂货店收银台旁的货架过道,
   主角蹲在第二层货架前」,不只写「商店」);
3. **环境光线**:时段 / 主光源方向 / 色温冷暖 / 明暗对比;
4. **氛围**:本集情绪基调,一句话;
5. **景别·运镜·构图**:单镜头一镜到底,写清起幅景别、运镜轨迹(推/摇/跟随到哪)、
   落幅景别与主体在画面的位置;
6. **声音**:环境音与音效描述写在 prompt_cn 结尾(风声、脚步、道具声),
   只写进正文、绝不进 negative——负面词框只留给画面规避;
7. 画面里不出现文字 / 字幕 / 水印;
8. {duration_s} 秒的节奏要贴着时长铺,不写镜头切换、不写多场景跳转(单段生成)。
negative 只写画面规避(畸变、多手多脚、文字、伪影等本格特有项)。"""
