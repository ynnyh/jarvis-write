"""润色引擎 Prompt:锁情节事实 + 去 AI 味(先诊断后治疗两段式)。

两条铁律:
1. 只改文笔,不改情节事实(锁定事实清单,润色后校验)
2. 默认去 AI 腔:检测驱动(命中点贴进 prompt 定点改写)+ 通用规则常驻

输出契约(借鉴 ai-flavor-remover 的"先诊断后治疗"):
【诊断】2-3 个最突出的 AI 味问题(类别+原句)→【策略】→【润色稿】
"""

# 去 AI 味的通用规则,始终注入(无论用户是否勾选"去AI味")
_DEAI_RULES = """\
【去除 AI 腔(务必遵守)】
- 删神态套话:"眼中闪过一丝""嘴角勾起""眸光一沉""邪魅一笑""空气仿佛凝固""命运的齿轮开始转动"等,换成具体动作
- 删稳妥套话:"沉默片刻""微微一笑""轻声说道""缓缓开口""淡淡地道"等,出现就必须改写
- 删总结过渡腔:"综上所述""总而言之""总的来说""由此可见""毫无疑问"等;段尾/章尾不得总结升华、点题说教
- 删论文式连接:"首先/其次/最后""一方面/另一方面""不仅……而且",以及"此外/而且/综上"式生硬过渡
- 删 hedge 词:"通常""往往""一般来说""某种意义上"
- 少用"仿佛""宛如""好似"等比喻连接词,能直接白描就白描;比喻限量,不堆砌
- 避免"不是……而是……""与其说……不如说……"等 AI 高频造句定式;拆掉排比堆砌
- 情绪靠动作、细节、对话呈现,不要直接写"他感到无比绝望""心中五味杂陈"这类情绪标签(Show, don't tell)
- 抽象描写必须挂具体锚点:数字、具名事物、感官细节,不写"一种难以言喻的氛围";尤其把脑内/心里的"涟漪、潮水"、"仿佛有人在远方呼唤""无形的手"这类无锚点空镜改成具体动作、身体反应或想到的实物
- 句式节奏:长短句交错,不得连续 3 句等长;破折号每 300 字最多 1 处;分号能改句号就改句号
- 保留人物特有的语气和口吻,不要把所有人都改成同一种"高级"腔调
"""

# 两段式输出契约(诊断 → 策略 → 润色稿),整章与片段共用
_OUTPUT_CONTRACT = """\
【输出契约:严格按三段输出,先诊断后治疗】
【诊断】列出本文最突出的 2-3 个 AI 味问题(类别 + 原句摘录,各一行)
【策略】每个问题对应的修改策略(各一句话)
【润色稿】润色后的完整文本(此标记之后只有正文,不要任何解释)
"""

# =============== 定向去味重写(自愈闭环:检测超标 → 只改问题处,其余原样) ===============
# 与整章润色的区别:这是"外科手术"——只改检测命中的句子、统计诊断点出的问题,
# 以及全文同类毛病,不重润好句子(全文重润慢/贵/会引入新 AI 味)。喂 命中句 +
# 统计诊断(advice)+ 配对反例 + 文风范本(正向锚),直接输出去味后的完整正文。
DEAI_REWRITE_PROMPT = """\
你是资深文学编辑。下面这章正文经 AI 味检测,仍有较明显的 AI 腔。请做一次「定向去味」重写:只针对下面点出的问题动刀,把 AI 腔改成人话;写得好的地方原样保留。

【必须锁定的情节(不得改动)】
情节走向、人物行为、对话实质、时间地点因果、伏笔安排一律不变;不新增原文没有的事件/人物/道具/设定,不删任何情节事实。

【本次检测命中的 AI 腔句子(逐条改写到位)】
{flavor_hits}

{advice_block}
{pairwise}
{style_directives}
改写要求:
1. 只改上面点出的问题句、问题段,以及全文里的同类毛病;没被点到、又写得干净的句子保持原样
2. 命中的套话换成具体的动作、细节、对话或环境;情绪不直说,靠画面呈现(Show, don't tell)
3. 段尾不总结、不升华、不点题;比喻克制;句式长短交错,别再等长
4. 篇幅与原文相当(±10%),不要因为去味就砍情节或大幅缩水

【待去味的正文】
{draft_text}

只输出去味后的完整正文,不要诊断、不要解释、不要任何标记:
"""


